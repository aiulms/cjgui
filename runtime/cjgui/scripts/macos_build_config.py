#!/usr/bin/env python3
"""Bounded cjpm build inputs for the ordinary macOS runner.

cjpm 1.1.3 merges same-name FFI entries from dependencies before the app's.
Pin the framework declaration as well as the application declaration to the
application's verified native cache. cjpm requires regular source files inside
each module, so keep one read-only production-source snapshot per application,
updated by content, while retaining the original application's target. This is
generated input, never another editable framework checkout or compiler wrapper.
"""
from __future__ import annotations

import argparse
import copy
import hashlib
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import sys
import tempfile

if sys.version_info < (3, 11):
    raise SystemExit("cjgui macOS runner requires Python 3.11+ (stdlib tomllib)")
import tomllib

FORMAT = 1
MAP_NAME = "cjgui-native-link.map"


def digest(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def read_manifest(root: Path) -> dict:
    with (root / "cjpm.toml").open("rb") as source:
        result = tomllib.load(source)
    if "workspace" in result or not isinstance(result.get("package"), dict):
        raise ValueError("macOS runner requires a single-package cjpm.toml")
    return result


def resolve(root: Path, value: str) -> Path:
    return (root / value).resolve()


def relocate(value, root: Path):
    if isinstance(value, dict):
        return {key: str(resolve(root, item)) if key == "path" and isinstance(item, str)
                else relocate(item, root) for key, item in value.items()}
    if isinstance(value, list):
        return [relocate(item, root) for item in value]
    return value


def toml_value(value) -> str:
    if isinstance(value, str):
        return json.dumps(value, ensure_ascii=False)
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return repr(value)
    if isinstance(value, list):
        return "[" + ", ".join(toml_value(item) for item in value) + "]"
    if isinstance(value, dict):
        return "{ " + ", ".join(toml_value(key) + " = " + toml_value(item)
                                 for key, item in value.items()) + " }"
    raise ValueError(f"unsupported cjpm configuration value: {type(value).__name__}")


def write_manifest(path: Path, data: dict) -> None:
    # Only serialize configuration. Preserve every existing key/value, including
    # profile/custom compiler options; validate the generated TOML independently.
    # cjpm 1.1.3 does not discover every local dependency from a top-level
    # inline dependencies value. Use ordinary table sections, including nested
    # dependency tables, instead of merely TOML-equivalent inline dictionaries.
    lines = ["# Generated by the CJGUI macOS runner from the original manifests."]

    def section(table, keys=()):
        if keys:
            lines.append("[" + ".".join(toml_value(key) for key in keys) + "]")
        for key, value in table.items():
            if not isinstance(value, dict):
                lines.append(toml_value(key) + " = " + toml_value(value))
        for key, value in table.items():
            if isinstance(value, dict):
                section(value, keys + (key,))

    section(data)
    text = "\n".join(lines) + "\n"
    if tomllib.loads(text) != data:
        raise ValueError("cjpm configuration did not round-trip")
    path.parent.mkdir(parents=True, exist_ok=True)
    if not path.exists() or path.read_text() != text:
        path.write_text(text)


def directory_alias(path: Path, source: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.is_symlink():
        if path.resolve() != source.resolve():
            path.unlink()
        else:
            return
    if path.exists():
        raise ValueError(f"generated directory alias is occupied: {path}")
    path.symlink_to(source, target_is_directory=True)


def snapshot_sources(source: Path, destination: Path, include_tests: bool = False,
                     source_names: set[str] | None = None) -> dict[str, str]:
    # Cjpm 1.1.3 rejects out-of-module directories and ignores source symlinks.
    # Only .cj inputs are copied, with no target/native/assets tree. Framework
    # internal tests stay outside this normal input; app tests remain runnable.
    # Reuse equal bytes; removed inputs are retired only from our previous index.
    if destination.is_symlink():
        destination.unlink()
    destination.mkdir(parents=True, exist_ok=True)
    index_path = destination.parent / "source-index.json"
    previous = json.loads(index_path.read_text()) if index_path.exists() else {}
    sources = {path.relative_to(source).as_posix(): path for path in source.rglob("*.cj")
               if path.is_file() and not path.is_symlink() and (include_tests or not path.name.endswith("_test.cj"))
               and (source_names is None or path.relative_to(source).as_posix() in source_names)}
    for path in destination.rglob("*.cj"):
        relative = path.relative_to(destination).as_posix()
        if relative not in sources:
            if relative not in previous:
                raise ValueError(f"unowned source in generated build inputs: {path}")
            path.unlink()
    # Record ownership before copying so an interrupted preparation can retire
    # its own removed inputs on the next attempt without deleting unknown files.
    index_path.write_text(json.dumps({name: digest(path) for name, path in sources.items()}, indent=2) + "\n")
    copied = {}
    for relative, path in sources.items():
        output = destination / relative
        output.parent.mkdir(parents=True, exist_ok=True)
        expected = digest(path)
        if output.is_symlink() or not output.exists() or digest(output) != expected:
            descriptor, name = tempfile.mkstemp(prefix=".cjgui-source-", dir=output.parent)
            os.close(descriptor)
            temporary = Path(name)
            try:
                shutil.copyfile(path, temporary)
                if digest(temporary) != expected:
                    raise ValueError(f"source changed while preparing build inputs: {path}")
                temporary.chmod(0o444)
                temporary.replace(output)
            finally:
                if temporary.exists():
                    temporary.unlink()
        copied[str(output)] = expected
    return copied


def source_snapshot(app: Path) -> dict[str, str]:
    result, visited = {}, set()

    def visit(root: Path):
        root = root.resolve()
        if root in visited:
            return
        visited.add(root)
        manifest = root / "cjpm.toml"
        data = read_manifest(root)
        result[str(manifest)] = digest(manifest)
        source_dir = resolve(root, data["package"].get("src-dir", "src"))
        for source in sorted(source_dir.rglob("*.cj")):
            if source.is_file() and (root == app.resolve() or not source.name.endswith("_test.cj")):
                result[str(source)] = digest(source)
        for dependency in data.get("dependencies", {}).values():
            if isinstance(dependency, dict) and "path" in dependency:
                visit(resolve(root, dependency["path"]))

    visit(app)
    return result


def prepare(app: Path, runtime: Path, native: Path, cache: Path) -> Path:
    app, runtime, native, cache = (path.resolve() for path in (app, runtime, native, cache))
    original = read_manifest(app)
    dependency = original.get("dependencies", {}).get("cjgui", {})
    if not isinstance(dependency, dict) or resolve(app, dependency.get("path", "")) != runtime:
        raise ValueError("application cjgui dependency must match the runner's framework directory")
    if resolve(app, original["package"].get("target-dir", "target")) != app / "target":
        raise ValueError("macOS runner requires the application's target directory")
    framework = relocate(read_manifest(runtime), runtime)
    framework_source = resolve(runtime, framework["package"].get("src-dir", "src"))
    prepared_sources = snapshot_sources(framework_source, cache / "framework/src")
    framework["package"]["src-dir"] = "src"
    framework.setdefault("ffi", {}).setdefault("c", {}).setdefault("cjgui_internal_renderer", {})["path"] = str(native)
    framework_path = cache / "framework/cjpm.toml"
    write_manifest(framework_path, framework)
    application = relocate(copy.deepcopy(original), app)
    application_source = resolve(app, original["package"].get("src-dir", "src"))
    prepared_sources.update(snapshot_sources(application_source, cache / "application/src", include_tests=True))
    (app / "target").mkdir(exist_ok=True)
    directory_alias(cache / "application/target", app / "target")
    application["package"]["src-dir"] = "src"
    application["package"]["target-dir"] = "target"
    application["package"]["link-option"] = application["package"].get("link-option", "") + " -t -map " + MAP_NAME
    application["dependencies"]["cjgui"]["path"] = str(framework_path.parent)
    for name, library in application.get("ffi", {}).get("c", {}).items():
        if name in ("cjgui_internal_renderer", "cjgui_macos_application_launcher"):
            library["path"] = str(native)
    application_path = cache / "application/cjpm.toml"
    write_manifest(application_path, application)
    renderer = native / "libcjgui_internal_renderer.a"
    record = {"format": FORMAT, "application_manifest": str(application_path),
              "framework_manifest": str(framework_path), "application_source": str(application_source),
              "framework_source": str(framework_source), "source_application": str(app), "target": str(app / "target"),
              "renderer_archive": str(renderer), "renderer_sha256": digest(renderer),
              "link_map": str(application_path.parent / MAP_NAME),
              "source_files": source_snapshot(app),
              "prepared_sources": prepared_sources,
              "generated_manifests": {str(path): digest(path) for path in (application_path, framework_path)}}
    libraries = [renderer]
    launcher = native / "libcjgui_macos_application_launcher.a"
    if launcher.exists():
        libraries.append(launcher)
    record["native_libraries"] = {str(path): digest(path) for path in libraries}
    fingerprint = native / "cjgui_macos_application_host.fingerprint"
    if fingerprint.exists():
        record["native_fingerprint"] = fingerprint.read_text()
    record["configurator_sha256"] = digest(Path(__file__))
    record["build_key"] = hashlib.sha256(json.dumps(record, sort_keys=True).encode()).hexdigest()
    (cache / "prepared.json").write_text(json.dumps(record, indent=2) + "\n")
    return application_path.parent


def verify(cache: Path, executable: Path) -> dict:
    record = json.loads((cache / "prepared.json").read_text())
    if source_snapshot(Path(record["source_application"])) != record["source_files"]:
        raise ValueError("source files or dependency declarations changed during compilation")
    for path, expected in (record["source_files"] | record["prepared_sources"] | record["generated_manifests"]).items():
        if not Path(path).is_file() or digest(Path(path)) != expected:
            raise ValueError(f"build input changed during compilation: {path}")
    expected = {Path(path).resolve(): value for path, value in record["native_libraries"].items()}
    for library, value in expected.items():
        if digest(library) != value:
            raise ValueError(f"native archive changed while cjpm consumed it: {library}")
    # This toolchain's map lists member basenames only. ld64/lld -t names the
    # actual archive opened after -L resolution; retain both original outputs.
    current_trace = cache / "current-link.log"
    trace = current_trace.read_text()
    pattern = r"^(.+lib(?:cjgui_internal_renderer|cjgui_macos_application_launcher)\.a)\(([^)]+)\)\s*$"
    if not re.search(pattern, trace, re.M):
        previous_path = cache / "build-provenance.json"
        previous = json.loads(previous_path.read_text()) if previous_path.exists() else {}
        if previous.get("build_key") != record["build_key"] or previous.get("executable_sha256") != digest(executable):
            raise ValueError("no fresh linker trace or identical verified executable")
        trace = (cache / "last-verified-link.log").read_text()
    choices = {}
    for archive, member in re.findall(pattern, trace, re.M):
        selected = Path(archive).resolve()
        if selected not in expected:
            raise ValueError(f"linker consumed an unapproved native archive: {selected}")
        choices.setdefault(str(selected), []).append(member)
    if set(choices) != {str(path) for path in expected}:
        raise ValueError("linker trace does not confirm every native archive")
    map_text = Path(record["link_map"]).read_text()
    for archive, members in choices.items():
        actual_members = subprocess.run(["ar", "-t", archive], capture_output=True, text=True, check=True).stdout.splitlines()
        for member in members:
            if member not in actual_members or not re.search(r"^\[\s*\d+\]\s+" + re.escape(member) + r"\s*$", map_text, re.M):
                raise ValueError(f"linked native member is not confirmed: {archive}({member})")
    (cache / "last-verified-link.log").write_text(trace)
    objects = choices[str(Path(record["renderer_archive"]).resolve())]
    record.update(actual_native_members=choices, actual_renderer_members=objects, executable=str(executable.resolve()),
                  executable_sha256=digest(executable), verified=True)
    (cache / "build-provenance.json").write_text(json.dumps(record, indent=2) + "\n")
    return record


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    commands = parser.add_subparsers(dest="command", required=True)
    setup = commands.add_parser("prepare")
    for name in ("app", "runtime", "native", "cache"):
        setup.add_argument(name, type=Path)
    check = commands.add_parser("verify")
    check.add_argument("cache", type=Path)
    check.add_argument("executable", type=Path)
    args = parser.parse_args()
    if args.command == "prepare":
        print(prepare(args.app, args.runtime, args.native, args.cache))
    else:
        result = verify(args.cache, args.executable)
        print("cjgui macOS application host: renderer_link=verified archive=" + result["renderer_archive"] +
              " sha256=" + result["renderer_sha256"] + " members=" + str(len(result["actual_renderer_members"])))


if __name__ == "__main__":
    try:
        main()
    except (ValueError, OSError, tomllib.TOMLDecodeError) as error:
        raise SystemExit("cjgui macOS build configuration: " + str(error))
