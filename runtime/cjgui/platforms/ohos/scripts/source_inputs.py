#!/usr/bin/env python3
"""Enumerate source/config inputs reachable from this lab's actual cjpm entry."""
import hashlib
import json
import os
from pathlib import Path
import sys
import tomllib


def verify_frozen_inputs(manifest, copied_source=None, copied_target=None):
    frozen = json.loads(manifest.read_text())
    allowed = {'CJGUI_PLATFORM', 'CJGUI_SHARED_CORE_SRC', 'PHAROS_PRODUCT_ROOT'}
    for name, expected in frozen.get('bindings', {}).items():
        if name not in allowed or not os.environ.get(name) or Path(os.environ[name]).resolve() != Path(expected).resolve():
            raise ValueError(f'input binding changed: {name}')
    roots = frozen['roots']
    if not roots:
        raise ValueError('empty frozen input manifest')
    if copied_source is not None:
        roots = [row for row in roots if Path(row['path']).resolve() == copied_source.resolve()]
        if len(roots) != 1:
            raise ValueError('copied source is not uniquely frozen')
    for row in roots:
        root = copied_target if copied_target is not None else Path(row['path'])
        if root.is_symlink() or not (root.is_dir() or root.is_file()):
            raise ValueError(f'input directory missing or redirected: {root}')
        if root.is_file():
            if {'': hashlib.sha256(root.read_bytes()).hexdigest()} != row['files']:
                raise ValueError(f'input bytes changed: {root}')
            continue
        actual = {}
        for path in root.rglob('*'):
            # Bytecode caches are generated by Python, rather than build inputs.
            if '__pycache__' in path.relative_to(root).parts:
                continue
            if path.is_symlink():
                raise ValueError(f'input redirected: {path}')
            if path.is_file():
                actual[path.relative_to(root).as_posix()] = hashlib.sha256(path.read_bytes()).hexdigest()
        if not actual or actual != row['files']:
            raise ValueError(f'input file set or bytes changed: {root}')


def source_inputs(lab):
    visited = set()
    inputs = set()

    def visit(module):
        module = module.resolve(strict=True)
        if module in visited:
            return
        visited.add(module)
        manifest = module / 'cjpm.toml'
        data = tomllib.loads(manifest.read_text())
        inputs.add(manifest)
        package = data['package']
        sources = (module / package.get('src-dir', 'src')).resolve(strict=True)
        if not sources.is_dir():
            raise ValueError(f'package source is not a directory: {sources}')
        inputs.update(p for p in sources.rglob('*') if p.is_file())
        dependencies = [data.get('dependencies', {})]
        dependencies += [target.get('dependencies', {}) for target in data.get('target', {}).values()
                         if isinstance(target, dict)]
        for table in dependencies:
            for dependency in table.values():
                if isinstance(dependency, dict) and 'path' in dependency:
                    visit(module / dependency['path'])

    visit(lab / 'entry')
    for name in ('cpp', 'ets', 'resources'):
        directory = lab / 'entry/src/main' / name
        if directory.is_dir():
            inputs.update(p for p in directory.rglob('*') if p.is_file())
    return sorted(inputs, key=os.fsencode)


if __name__ == '__main__':
    if len(sys.argv) in (3, 5) and sys.argv[1] == '--verify-frozen-inputs':
        try:
            verify_frozen_inputs(*map(Path, sys.argv[2:]))
        except (ValueError, OSError, KeyError, TypeError) as error:
            print(f'SOURCE-DRIFT {error}', file=sys.stderr)
            sys.exit(2)
        print('SOURCE-BOUND frozen inputs verified')
        sys.exit(0)
    paths = source_inputs(Path(sys.argv[1]))
    # Emit only after the complete dependency graph has passed validation.
    for path in paths:
        sys.stdout.buffer.write(os.fsencode(path) + b'\0')
